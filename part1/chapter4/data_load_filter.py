import pandas as pd

# ------------------------------------------
# 1. 실습용 데이터 생성 및 저장 (시험 환경 시뮬레이션)
# ------------------------------------------
data = {
    '이름': ['지수', '제니', '로제', '리사', '코딩'],
    '나이': [28, 27, 26, 26, 30],
    '부서': ['개발', '디자인', '기획', '개발', '기획'],
    '점수': [85, 90, 95, 88, 100]
}
df_temp = pd.DataFrame(data)
df_temp.to_csv('aice_practice.csv', index=False) # 데이터 저장 (인덱스 제외)

# ------------------------------------------
# 2. 데이터 불러오기
# ------------------------------------------
print("--- 2. 데이터 불러오기 ---")
df = pd.read_csv('aice_practice.csv')
print(df)
print("\n")

# ------------------------------------------
# 3. 데이터 선택 및 범위 지정
# ------------------------------------------
print("--- 3. 단일 열 및 여러 열 선택  ---")
print("단일 열 선택 (나이):\n", df['나이'])
print("\n여러 열 선택 (이름, 점수):\n", df[['이름', '점수']])

print("\n--- 행 범위 지정 (슬라이싱)  ---")
print("0~2번 행 선택 (끝 번호 3 제외):\n", df[0:3])

# ------------------------------------------
# 4. 특정 행과 열 동시 선택 (loc vs iloc)
# ------------------------------------------
print("\n--- 4. loc (이름/라벨 기준)  ---")
# 주의: loc는 범위 지정 시 끝 범위를 포함합니다. (0:2 이면 0, 1, 2행 모두 선택)
print("loc로 0~2행, '이름'부터 '부서'열까지 선택:\n", df.loc[0:2, '이름':'부서'])

print("\n--- 4. iloc (숫자/위치 기준)  ---")
# 주의: iloc는 범위 지정 시 끝 범위를 제외합니다. (0:2 이면 0, 1행만 선택)
print("iloc로 0~1행, 0~1열 선택:\n", df.iloc[0:2, 0:2])

# ------------------------------------------
# 5. 조건으로 데이터 선택 (Boolean Indexing)
# ------------------------------------------
print("\n--- 5. 조건 필터링  ---")
# 단일 조건
print("나이가 27 이상인 데이터:\n", df[df['나이'] >= 27])

# 복합 조건 (AND: &, OR: |) - 각 조건을 반드시 괄호()로 묶어야 합니다!
print("\n개발 부서이면서(&) 점수가 86 이상인 데이터:\n", df[(df['부서'] == '개발') & (df['점수'] >= 86)])

